"""Message plumbing shared by every Experiment 9 node.

Students do not edit this file. It only converts between ROS messages and plain
NumPy arrays, so the three functions in ``experiment9_student.fusion`` can be
pure mathematics and can be unit tested without a running simulator.
"""

import numpy as np

# PointCloud2 datatype codes from sensor_msgs/PointField
FLOAT32 = 7
UINT16 = 4
INT16 = 3
FLOAT64 = 8


def read_xyz(msg):
    """Return ``(N, 3)`` float32 points from a PointCloud2 message.

    Reads the buffer directly instead of going through
    ``sensor_msgs_py.point_cloud2``: the teaching image pins Humble, where the
    helper's return type changed between releases, and a silent struct-array
    versus tuple mismatch is a bad way to spend lab time.
    """
    offsets = {}
    for field in msg.fields:
        if field.name in ('x', 'y', 'z'):
            if field.datatype != FLOAT32:
                raise ValueError(f'field {field.name} must be FLOAT32, got datatype {field.datatype}')
            offsets[field.name] = field.offset
    if len(offsets) != 3:
        raise ValueError('cloud must contain x, y and z fields')
    if msg.is_bigendian:
        raise ValueError('big-endian clouds are not supported by this teaching build')

    dtype = np.dtype({
        'names': ['x', 'y', 'z'],
        'formats': ['<f4', '<f4', '<f4'],
        'offsets': [offsets['x'], offsets['y'], offsets['z']],
        'itemsize': msg.point_step,
    })
    count = msg.width * msg.height
    if count == 0:
        return np.zeros((0, 3), dtype=np.float32)
    structured = np.frombuffer(bytes(msg.data), dtype=dtype, count=count)
    points = np.stack([structured['x'], structured['y'], structured['z']], axis=1)
    points = np.asarray(points, dtype=np.float32)
    return points[np.isfinite(points).all(axis=1)]


def write_xyz(points, frame_id, stamp):
    """Build a PointCloud2 message with x/y/z float32 fields from ``(N, 3)``."""
    from sensor_msgs.msg import PointCloud2, PointField

    points = np.ascontiguousarray(np.asarray(points, dtype='<f4').reshape(-1, 3))
    message = PointCloud2()
    message.header.stamp = stamp
    message.header.frame_id = frame_id
    message.height = 1
    message.width = points.shape[0]
    message.fields = [
        PointField(name='x', offset=0, datatype=FLOAT32, count=1),
        PointField(name='y', offset=4, datatype=FLOAT32, count=1),
        PointField(name='z', offset=8, datatype=FLOAT32, count=1),
    ]
    message.is_bigendian = False
    message.point_step = 12
    message.row_step = 12 * points.shape[0]
    message.is_dense = True
    message.data = points.tobytes()
    return message


def decode_depth(msg):
    """Return ``(H, W)`` float32 depth in metres.

    Gazebo Fortress publishes ``R_FLOAT32``; a real RealSense publishes
    ``16UC1`` with millimetres. Both arrive through the same bridge topic name,
    so the node has to cope with either.
    """
    height, width = msg.height, msg.width
    encoding = (msg.encoding or '').lower()
    if encoding in ('32fc1', '32fc'):
        values = np.frombuffer(bytes(msg.data), dtype='<f4')
        scale = 1.0
    elif encoding in ('16uc1', 'mono16'):
        values = np.frombuffer(bytes(msg.data), dtype='<u2')
        scale = 0.001
    else:
        raise ValueError(f'unsupported depth encoding: {msg.encoding!r}')
    expected = height * width
    if values.size < expected:
        raise ValueError(f'depth buffer holds {values.size} values, expected {expected}')
    if msg.is_bigendian:
        raise ValueError('big-endian depth images are not supported by this teaching build')
    return (values[:expected].reshape(height, width) * scale).astype(np.float32)


def intrinsics_from_camera_info(msg):
    """Return ``{'fx','fy','cx','cy','width','height'}`` from a CameraInfo."""
    k = msg.k
    if len(k) < 9:
        raise ValueError('camera_info.k must hold 9 values')
    return {
        'fx': float(k[0]), 'fy': float(k[4]),
        'cx': float(k[2]), 'cy': float(k[5]),
        'width': int(msg.width), 'height': int(msg.height),
    }


def extrinsic(translation, rotation_rowmajor):
    """Build ``(R, t)`` from flat parameter arrays.

    ROS 2 parameters cannot carry nested arrays, so the 3x3 rotation is stored
    as nine row-major floats in the YAML file.
    """
    rotation = np.asarray(rotation_rowmajor, dtype=np.float64)
    if rotation.size != 9:
        raise ValueError('rotation must hold 9 values, row major')
    rotation = rotation.reshape(3, 3)
    translation = np.asarray(translation, dtype=np.float64)
    if translation.size != 3:
        raise ValueError('translation must hold 3 values')
    # A cheap sanity check: a rotation matrix is orthonormal with det +1. This
    # catches scaled, sheared and mirrored matrices - the three mistakes that
    # make a cloud silently land several metres away. It does NOT catch a
    # transposed rotation: the transpose is also a valid rotation, just the
    # wrong direction, and only the wall check in cloud_check.py sees that.
    if not np.allclose(rotation @ rotation.T, np.eye(3), atol=1e-3):
        raise ValueError('rotation matrix is not orthonormal - check the derivation')
    if not np.isclose(np.linalg.det(rotation), 1.0, atol=1e-3):
        raise ValueError('rotation matrix must have determinant +1 (no mirroring)')
    return rotation, translation
